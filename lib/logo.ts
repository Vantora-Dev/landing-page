/** Wordmark placement beside the mark: cap height is 40 of the mark's 104. */
const WORDMARK_SCALE = 40 / 701;
export const WORDMARK_TRANSFORM = `translate(128.06 27) scale(${WORDMARK_SCALE})`;

/** Full lockup (mark + wordmark) box. */
export const LOGO_WIDTH = 476;
export const LOGO_HEIGHT = MARK.height;

export type LogoTone = "light" | "dark";

/**
 * The whole lockup as an SVG string, for places that can't render JSX: the
 * Open Graph image and the icon renders. `tone` is the BACKGROUND it sits on.
 */
export function logoSvg(tone: LogoTone, gradientId = "lg-mark"): string {
  const ink = tone === "dark" ? "#fafaf9" : LOGO_COLORS.indigo;
  const squares = MARK.squares
    .map(
      (s) =>
        `<rect x="${s.x}" y="${s.y}" width="${MARK.squareSize}" height="${MARK.squareSize}" rx="${MARK.squareRx}"/>`,
    )
    .join("");
  const { stem } = MARK;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${LOGO_WIDTH} ${LOGO_HEIGHT}">` +
    `<defs><linearGradient id="${gradientId}" gradientUnits="userSpaceOnUse" x1="0" y1="12" x2="96" y2="104">` +
    `<stop offset="0" stop-color="${LOGO_COLORS.markFrom}"/><stop offset="0.55" stop-color="${LOGO_COLORS.markMid}"/><stop offset="1" stop-color="${LOGO_COLORS.markTo}"/>` +
    `</linearGradient></defs>` +
    `<path fill="url(#${gradientId})" d="${MARK.outline}"/>` +
    `<rect fill="url(#${gradientId})" x="${stem.x}" y="${stem.y}" width="${stem.width}" height="${stem.height}" rx="${stem.rx}"/>` +
    `<g fill="${LOGO_COLORS.orange}">${squares}</g>` +
    `<g transform="${WORDMARK_TRANSFORM}"><path fill="${ink}" d="${WORDMARK.laundro}"/><path fill="${LOGO_COLORS.orange}" d="${WORDMARK.grid}"/></g>` +
    `</svg>`
  );
}
